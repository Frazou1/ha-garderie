    /// <summary>Textes saisis (cle -> texte), sans les textes par defaut / Entered texts, without defaults.</summary>
    public static Dictionary<string, string> Lire(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return new();
        try { return JsonSerializer.Deserialize<Dictionary<string, string>>(json) ?? new(); }
        catch (JsonException) { return new(); }
    }

    /// <summary>Garde seulement ce qui differe du texte par defaut ; null si rien / Keeps only non-default texts.</summary>
    public static string? Ecrire(IReadOnlyDictionary<string, string?> saisies)
    {
        var d = new Dictionary<string, string>();
        foreach (var s in Sections)
        {
            var t = Normaliser(saisies.GetValueOrDefault(s.Cle));
            if (t.Length > 0 && t != Normaliser(s.Texte)) d[s.Cle] = t;
        }
        return d.Count == 0 ? null : JsonSerializer.Serialize(d);
    }

    public static string Normaliser(string? t) => (t ?? "").Replace("\r\n", "\n").Trim('\n', ' ', '\r');

    /// <summary>Texte d'une section (saisi, sinon par defaut) / Section text (entered, else default).</summary>
    public static string Texte(SectionRegie s, IReadOnlyDictionary<string, string> saisies) =>
        saisies.TryGetValue(s.Cle, out var t) && t.Length > 0 ? t : s.Texte;

    private const string Blanc = "________";

    private static string Heure(TimeOnly? h) => h is { } x ? $"{x.Hour}h{x.Minute:00}" : Blanc;

    /// <summary>Regie complete en balisage, valeurs remplacees / Full rules as markup, values filled in.</summary>
    public static string Composer(Parametres p)
    {
        var saisies = Lire(p.RegieSections);
        var b = new StringBuilder("# Régie Interne\n\n> ## {rsge}\n> ## Mise à jour {mise_a_jour}\n");
        string? partie = null;
        foreach (var s in Sections)
        {
            var texte = Texte(s, saisies);
            if (texte.Trim() == Retiree) continue;
            if (s.Partie != partie)
            {
                b.Append("## ").Append(s.Partie).Append('\n');
                if (s.Titre is not null) b.Append('\n');
                partie = s.Partie;
            }
            if (s.Titre is not null) b.Append("### ").Append(s.Titre).Append('\n');
            b.Append(texte.Trim('\n')).Append("\n\n");
        }
        var feries = Feries.Descriptions;
        var mois = Temps.VersLocal(p.RegieModifieeLe ?? DateTime.UtcNow).ToString("MMMM yyyy", new CultureInfo("fr-CA"));
        string V(string? v) => string.IsNullOrWhiteSpace(v) ? Blanc : v.Trim();
        return b.ToString()
            .Replace("{mention_lpc}", (p.ContratMentionLpc ?? TextesContrat.MentionLpc).Trim())
            .Replace("{feries}", string.Join("\n", feries.Select(f => "- " + f)))
            .Replace("{nb_feries}", $"{Nombre(feries.Count)} ({feries.Count})")
            .Replace("{rsge}", V(p.NomRsge)).Replace("{garderie}", V(p.NomGarderie))
            .Replace("{ouverture}", Heure(p.HeureOuverture)).Replace("{fermeture}", Heure(p.HeureFermeture))
            .Replace("{tarif}", V(p.RegieTarif)).Replace("{jour_paiement}", V(p.RegieJourPaiement)).Replace("{frais_retard}", V(p.RegieFraisRetard))
            .Replace("{mise_a_jour}", char.ToUpper(mois[0]) + mois[1..])
            .TrimEnd('\n') + "\n";
    }

    private static string Nombre(int n) => n switch
    {
        10 => "dix", 11 => "onze", 12 => "douze", 13 => "treize", 14 => "quatorze", 15 => "quinze", _ => n.ToString(CultureInfo.InvariantCulture),
    };

    public static byte[] Pdf(Parametres p) => RegiePdf.Generer(Composer(p));
